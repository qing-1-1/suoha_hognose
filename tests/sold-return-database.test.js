const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),{randomUUID}=require('node:crypto'),{PGlite}=require('@electric-sql/pglite');
test('sold returns preserve history, are atomic and idempotent, and permit a later sale',async()=>{
 const db=new PGlite(),actor='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',listing=randomUUID();
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;create schema storage;
   create table auth.users(id uuid primary key);insert into auth.users values('${actor}');
   create table profiles(id uuid primary key,active boolean);insert into profiles values('${actor}',true);
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('app.actor',true),'')::uuid$$;
   create function can_edit_app() returns boolean language sql as $$select current_setting('app.editor',true)='yes'$$;
   create table snakes(id text primary key,status text,origin text,series text,sex text,birth_date date,gene_text text,dam_id text,sire_id text);
   create table genes(id text primary key,name_zh text);create table snake_genes(snake_id text,gene_id text,state text,probability numeric);
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(id uuid,bucket_id text,name text);alter table storage.objects enable row level security;
   grant usage on schema public,auth,storage to anon,authenticated,service_role;
   grant select,update on snakes to authenticated;
   create table room_workspace(id int primary key);insert into room_workspace values(1);
   create table auctions(listing_id uuid,status text);
   create table payment_receipts(inquiry_id uuid,status text);`);
  for(const file of ['019_public_catalog_and_sales.sql','023_inventory_libraries.sql'])await db.exec(fs.readFileSync('supabase/migrations/'+file,'utf8'));
  await db.exec(`alter table inventory_transfers add column assessment text;
   insert into snakes(id,status,origin,gene_text,dam_id,sire_id) values('A','sold','purchased','原始基因','MOM','DAD'),('B','sold','produced','幼体基因','MOM','DAD'),('C','active','purchased',null,null,null),('D','active','purchased',null,null,null),('Z','deceased',null,null,null,null);
   insert into specimen_listings(id,snake_id,slug,title,sale_status,published) values('${listing}','A','a','A','sold',true),(gen_random_uuid(),'C','c','C','sold',true);
   insert into purchase_inquiries(request_id,listing_id,customer_name,contact,fingerprint,status,agreed_price) values(gen_random_uuid(),'${listing}','客户','contact','test','completed',1234);
   insert into specimen_media(listing_id,storage_path) values('${listing}','a/original.webp');
   insert into payment_receipts select id,'confirmed' from purchase_inquiries;`);
  await db.exec(fs.readFileSync('supabase/migrations/046_return_sold_animals.sql','utf8'));
  const call=(ids=['A','B','C'],key=randomUUID(),reason='历史误标，更正回库')=>db.query('select return_sold_animals($1,$2,$3) data',[ids,reason,key]);
  await db.exec('set role anon');await assert.rejects(call(),/permission denied/);
  await db.exec('reset role;set role authenticated');await assert.rejects(call(),/Not authorized/);
  await db.exec("set app.editor='yes'");await assert.rejects(call(),/Not authorized/);
  await db.exec(`set app.actor='${actor}'`);
  await assert.rejects(db.query("update snakes set status='active' where id='A'"),/separate correction workflow/);
  await assert.rejects(call(['A','MISSING']),/不存在/);
  await assert.rejects(call(['A','Z']),/不是可回库/);
  await assert.rejects(call(['A','D']),/不是可回库/);
  await assert.rejects(call([],randomUUID()),/请选择/);
  await assert.rejects(call(['A'],randomUUID(),''),/原因/);
  // A later failure must roll back an earlier animal, history and freed sales reservation.
  assert.equal((await db.query("select status from snakes where id='A'")).rows[0].status,'sold');
  assert.equal((await db.query('select count(*) n from sold_return_history')).rows[0].n,0);
  await db.exec(`reset role;insert into auctions values('${listing}','open');set role authenticated`);
  await assert.rejects(call(),/进行中的拍卖/);
  await db.exec("reset role;delete from auctions;update payment_receipts set status='pending';set role authenticated");
  await assert.rejects(call(),/待核实付款/);
  await db.exec("reset role;update payment_receipts set status='confirmed';update purchase_inquiries set status='reserved';set role authenticated");
  await assert.rejects(call(),/未结束交易/);
  await db.exec("reset role;update purchase_inquiries set status='completed';set role authenticated");
  const key=randomUUID(),returned=(await call(['C','B','A','A'],key)).rows[0].data;
  assert.deepEqual(returned,{returned_ids:['A','B','C'],count:3});
  assert.deepEqual((await call(['A','B','C'],key)).rows[0].data,returned);
  await assert.rejects(call(['A'],key),/冲突/);
  await assert.rejects(call(['A','B','C'],key,'另一原因'),/冲突/);
  await assert.rejects(call(),/不是可回库/);
  assert.deepEqual((await db.query("select status,inventory_library from snakes where id in ('A','B','C') order by id")).rows,Array.from({length:3},()=>({status:'active',inventory_library:'stock'})));
  assert.deepEqual((await db.query("select gene_text,dam_id,sire_id from snakes where id='A'")).rows[0],{gene_text:'原始基因',dam_id:'MOM',sire_id:'DAD'});
  assert.equal((await db.query('select count(*) n from sold_return_history')).rows[0].n,3);
  assert.equal((await db.query('select count(*) n from inventory_transfers')).rows[0].n,3);
  assert.deepEqual((await db.query('select published,sale_status from specimen_listings')).rows,[{published:false,sale_status:'display'},{published:false,sale_status:'display'}]);
  const old=(await db.query('select * from purchase_inquiries')).rows[0];assert.equal(old.status,'completed');assert.ok(old.returned_at);assert.equal(Number(old.agreed_price),1234);
  assert.equal((await db.query('select action from sales_activity')).rows[0].action,'returned_to_stock');
  await assert.rejects(db.query('delete from sold_return_history'),/permission denied/);
  await assert.rejects(db.query('update purchase_inquiries set returned_at=null'),/permission denied/);
  // Use the real sales RPC to complete a second sale, preserving the first order.
  await db.query("update specimen_listings set published=true,sale_status='available' where id=$1",[listing]);
  await db.exec('reset role');
  const second=(await db.query("select submit_purchase_inquiry($1,$2,'客户2','contact2','','fingerprint2') data",[randomUUID(),listing])).rows[0].data;
  await db.exec('set role authenticated');
  const inquiry=(await db.query('select id from purchase_inquiries where reference=$1',[second.reference])).rows[0].id;
  for(const action of ['reserve','paid','deliver','complete'])await db.query('select manage_specimen_sale($1,$2,$3,$4,$5)',[inquiry,action,'二次交易','2099-01-01',2000]);
  await call(['A']);
  assert.equal((await db.query('select count(*) n from purchase_inquiries where returned_at is not null and status=\'completed\'')).rows[0].n,2);
  assert.equal((await db.query("select count(*) n from sold_return_history where individual_id='A'")).rows[0].n,2);
  await db.exec('reset role');
  assert.equal((await db.query('select count(*) n from specimen_media')).rows[0].n,1);
  assert.equal((await db.query("select count(*) n from payment_receipts where status='confirmed'")).rows[0].n,1);
  await db.exec("set role authenticated;set app.editor='no'");
  assert.equal((await db.query('select count(*) n from sold_return_history')).rows[0].n,0);
  await assert.rejects(call(['A'],key),/Not authorized/);
 }finally{await db.close();}
});
