const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {randomUUID}=require('node:crypto');
const {PGlite}=require('@electric-sql/pglite');
const M=require('../js/room-model');
const sql=name=>fs.readFileSync('supabase/migrations/'+name+'.sql','utf8');

test('049 repairs legacy UUID feeding function and guards without losing history',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;
   create table auth.users(id uuid primary key);create table profiles(id uuid primary key,role text,active boolean);
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function can_edit_app() returns boolean language sql security definer as $$select exists(select 1 from profiles where id=auth.uid() and active and role in ('admin','editor'))$$;
   create table snakes(id text primary key,status text);
   create table snake_measurements(id bigint generated always as identity primary key,snake_id text references snakes(id),record_kind text default 'measurement',measured_at date,feeding_status text,condition_note text);
   grant usage on schema public,auth to anon,authenticated;
   grant select,update,delete on snake_measurements to authenticated;
   insert into auth.users values('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa');
   insert into profiles values('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa','admin',true);
   insert into snakes values('Y022','active');
   insert into snake_measurements(snake_id,measured_at,condition_note) values('Y022','2020-01-01','保留原有观察');`);
  await db.exec(sql('039_room_workspace'));
  await db.exec(sql('040_room_rules_and_batches').replace('declare m public.snake_measurements.id%type;','declare m uuid;'));
  await db.exec('alter table room_measurement_write_guards alter column measurement_id type uuid using measurement_id::text::uuid');
  await db.exec("set request.jwt.claim.sub='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';set role authenticated");
  const cfg=M.defaultConfig();cfg.cabinets=[M.createCabinet({id:'rack',levels:[{count:1,height:300,boxWidth:350,boxDepth:460,boxHeight:240}]})];
  let state=(await db.query('select room_save_layout(0,$1,$2) data',[cfg,randomUUID()])).rows[0].data;
  const slot=cfg.cabinets[0].levels[0].slots[0].id;
  state=(await db.query('select room_assign($1,$2,$3,false,$4) data',[state.revision,'Y022',slot,randomUUID()])).rows[0].data;
  const payload={snake_id:'Y022',slot_id:slot,cabinet_id:'rack',planned_at:'2020-01-02T10:00:00Z',occurred_at:'2020-01-02T09:00:00Z',result:'offered',mouse_min_g:2,mouse_max_g:2,quantity:1,notes:''};
  const request=randomUUID(),revision=state.revision;
  const record=async(p,rev,req)=>(await db.query('select room_record_feeding($1,$2,$3) data',[rev,p,req])).rows[0].data;
  await db.exec("reset role;select setval(pg_get_serial_sequence('snake_measurements','id'),33,false);set role authenticated");
  await assert.rejects(record(payload,revision,request),/invalid input syntax for type uuid: "33"/);
  assert.deepEqual((await db.query('select room_snapshot() data')).rows[0].data,state);
  await db.exec('reset role');
  const repair=sql('049_room_feeding_measurement_type');await db.exec(repair);await db.exec(repair);
  await db.exec("select setval(pg_get_serial_sequence('snake_measurements','id'),33,false);set role authenticated");
  state=await record(payload,revision,request);
  assert.equal(Number(state.records[0].measurement_id),33);
  assert.match(state.records[0].id,/^[0-9a-f-]{36}$/i);
  assert.equal(state.revision,revision+1);
  assert.deepEqual(await record(payload,revision,request),state);
  state=await record({...payload,result:'fed',notes:'确认进食'},state.revision,randomUUID());
  assert.equal(state.records.length,1);assert.equal(Number(state.records[0].measurement_id),33);
  assert.equal(state.records[0].result,'fed');
  assert.match((await db.query('select feeding_status from snake_measurements where id=33')).rows[0].feeding_status,/已进食/);
  assert.equal((await db.query('select condition_note from snake_measurements where id=1')).rows[0].condition_note,'保留原有观察');
  await assert.rejects(db.query("update snake_measurements set condition_note='绕过管理' where id=33"),/该喂食记录由爬房管理/);
  await db.exec('reset role');
  assert.equal((await db.query('select count(*) n from room_measurement_write_guards')).rows[0].n,0);
  assert.equal((await db.query('select count(*) n from snake_measurements')).rows[0].n,2);
  await db.exec(repair);await db.exec('set role authenticated');
  assert.deepEqual((await db.query('select room_snapshot() data')).rows[0].data,state);
  await db.exec('reset role;set role anon');
  await assert.rejects(record(payload,state.revision,randomUUID()),/permission denied/);
 }finally{await db.close();}
});
